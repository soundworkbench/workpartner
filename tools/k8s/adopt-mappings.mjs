// Image compatibility defaults. Explicit operator targets take precedence.
export const imageMappings = Object.freeze({
  paths: Object.freeze({ '/opt/partner-next': '/opt/workpartner' }),
  ports: Object.freeze({ 3092: 25808 }),
});

export function mappedPath(value) {
  if (typeof value !== 'string') return value;
  for (const [from, to] of Object.entries(imageMappings.paths)) {
    if (value === from || value.startsWith(`${from}/`)) return to + value.slice(from.length);
  }
  return value;
}

export function mappedItem(source) {
  return { ...source,
    ...(source.path !== undefined ? { path: mappedPath(source.path) } : {}),
    ...(source.executable !== undefined ? { executable: mappedPath(source.executable) } : {}),
    ...(source.kind === 'port' ? { port: imageMappings.ports[source.port] ?? source.port } : {}),
  };
}

export function defaultDecision(item) {
  let reason = '';
  // Parent directory metadata changes are generated by startup. Do not drop
  // arbitrary descendants: custom executables and credentials need review.
  if ((item.kind === 'docker-diff' && ['/usr', '/usr/local', '/usr/local/bin', '/root', '/root/.gitconfig'].includes(item.path))
      || (item.kind === 'dotfile' && item.path === '/root/.gitconfig')) {
    reason = 'Old image startup-generated directory metadata or root Git configuration';
  }
  if (item.kind === 'process') {
    const executable = item.executable?.split('/').pop();
    if (['curl', 'sleep'].includes(executable)) reason = 'Transient command observed during inventory';
    if (executable === 'claude' && item.interactive === true) reason = 'Interactive CLI session observed during inventory; restart after migration';
  }
  return { decision: reason ? 'dropped' : '', method: '', reason, target: {} };
}
